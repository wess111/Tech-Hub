import assert from 'node:assert/strict';
import {PARTS,CABLES,freshState,install,canInstall,canRemove,sanitizeState,validate,postChecks} from '../assets/pc3d-rules.js';
const s=freshState();
assert.match(install(s,'cpu'),/motherboard/);
assert.equal(install(s,'motherboard'),null);
assert.match(install(s,'cpu'),/Secure/);
s.boardScrews=9;
assert.match(install(s,'cpu'),/Open/);
s.socketOpen=true;
assert.match(install(s,'cpu',1),/rotated/);
assert.equal(install(s,'cpu'),null);
assert.match(install(s,'cooler'),/latch/);
s.socketOpen=false;s.cpuLatched=true;
assert.match(install(s,'cooler'),/compound/);
s.paste=Array.from({length:41},()=>({y:0,z:0}));
assert.match(install(s,'cooler'),/Too much/);
s.paste=Array.from({length:7},()=>({y:0,z:0}));
assert.equal(install(s,'cooler'),null);s.coolerScrews=4;
assert.match(install(s,'ramA2'),/clips/);
for(const key of ['ramA2','ramB2']){s.clips[key]=true;assert.equal(install(s,key),null);assert.equal(s.clips[key],false);}
assert.match(install(s,'gpu'),/covers/);s.expansionOpen=true;assert.equal(install(s,'gpu'),null);
for(const key of ['psu','ssd','fan'])assert.equal(install(s,key),null);s.psuScrews=4;
assert.ok(postChecks(s).some(c=>!c.pass));
for(const key of ['atx','eps','gpuPower','cpuFan','powerSwitch'])s.cables[key]=[[-.9,.5,0],[-.9,3,0]];
assert.ok(postChecks(s).every(c=>c.pass),'Core power and hardware permit POST without front USB/audio');
assert.ok(validate(s).some(c=>!c.pass),'Full assembly still requires remaining cabling');
for(const key of Object.keys(CABLES))s.cables[key]=[[1.05,.5,0],[1.05,3,0]];
assert.ok(validate(s).every(c=>c.pass));
assert.match(canRemove(s,'psu'),/Disconnect/);
s.powered=true;assert.match(canRemove(s,'cooler'),/Switch off/);assert.match(canInstall(s,'motherboard'),/already/);
const restored=sanitizeState(JSON.parse(JSON.stringify(s)));
assert.equal(restored.installed.length,Object.keys(PARTS).length);assert.equal(Object.keys(restored.cables).length,10);assert.equal(restored.powered,false);assert.ok(validate(restored).every(c=>c.pass));
assert.deepEqual(sanitizeState({version:999}),freshState());
const corrupt=sanitizeState({version:2,installed:['unknown','cpu','cpu'],paste:[{y:999,z:0},{y:0,z:0}],cables:{unknown:[],atx:[[99,0,0],[1.18,3,0],[NaN,0,0]]}});
assert.deepEqual(corrupt.installed,['cpu']);assert.equal(corrupt.paste.length,1);assert.deepEqual(corrupt.cables.atx,[[1.05,3,0]]);
console.log('3D assembly rules passed: sequence, orientation, socket, clips, paste amount, cabling, POST separation, removal safety, and saved-state restoration.');
